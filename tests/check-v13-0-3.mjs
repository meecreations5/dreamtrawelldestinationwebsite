import fs from 'node:fs';
import assert from 'node:assert/strict';
import { packageFallback, packageImageSource } from '../lib/package-image.js';
const read=p=>fs.readFileSync(p,'utf8');
const packages=JSON.parse(read('data/packages.json'));
const sg=packages.find(p=>p.slug==='programme-singapore-family-discoveries');
const dx=packages.find(p=>p.slug==='programme-dubai-corporate-incentive');
assert(sg.image.includes('photo-1525625293386'), 'Singapore starter must use Singapore photo');
assert(dx.image.includes('photo-1512453979798'), 'Dubai starter must use Dubai photo');
assert(packageImageSource({...sg,image:'https://images.unsplash.com/photo-1542051841857-5f90071e7989'})===sg.image);
assert(packageImageSource({...dx,image:'https://images.unsplash.com/photo-1499856871958-5b9627545d1a'})===dx.image);
assert.equal(packageImageSource({...sg,image:'/assets/custom/singapore.jpg'}),'/assets/custom/singapore.jpg');
assert(packageFallback(sg).endsWith('svg'));
const detail=read('app/(site)/packages/[slug]/page.jsx');
for(const key of ['PackageGallery','PackageGuideTabs','packageImageSource','customise?package','dt-package-mobile-cta','aria-label="Breadcrumb"'])assert(detail.includes(key),key);
const gallery=read('components/package-gallery.jsx');
assert(gallery.startsWith("'use client'"));
assert(gallery.includes('photos.length>1')&&gallery.includes('aria-pressed'));
const tabs=read('components/package-guide-tabs.jsx');
assert(tabs.includes('role="tablist"')&&tabs.includes('aria-selected')&&tabs.includes('<DayAccordion'));
assert(tabs.includes('pack.exclusionsNote') && tabs.includes('Array.isArray(pack.days)'));
const editor=read('components/admin-workspace.jsx');
assert(editor.includes('function GalleryEditor(')&&editor.includes('gallery:${i}')&&editor.includes("'gallery','days'"));
assert(read('components/admin-panel.jsx').includes("key.startsWith('gallery:')"));
assert(read('lib/validation.js').includes('gallery: z.array(packageGalleryImageSchema).max(8).optional()'));
assert(read('firestore.rules').includes("'imageAlt','gallery'"));
const css=read('app/v13-0-3-polish.css');
for(const t of ['.dark-panel .advantages h2','.dark-panel .advantage-grid h3','.v11-area-details','.v12-contrast','.dt-gallery-stage','.dt-package-tablist','.dt-package-mobile-cta','var(--dt-cloud)'])assert(css.includes(t),t);
assert(css.includes('bottom:calc(73px + env(safe-area-inset-bottom,0px))'));
assert(read('app/layout.jsx').includes("import './v13-0-3-polish.css'"));
console.log('PASS: V13.0.3 brand contrast, known photo corrections, CMS gallery schema/rules, accessible package UX and dock positioning.');
