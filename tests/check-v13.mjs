import fs from 'node:fs';
import assert from 'node:assert/strict';
import {DEFAULT_THEME,THEME_PRESETS,sanitizeTheme,validateTheme,contrastRatio,themeVariables} from '../lib/site-theme.js';
const text=file=>fs.readFileSync(file,'utf8');
assert.equal(validateTheme(DEFAULT_THEME),'');
for(const preset of THEME_PRESETS)assert.equal(validateTheme(preset.palette),'',`contrast: ${preset.id}`);
assert.ok(validateTheme({...DEFAULT_THEME,navy:'#FFFFFF'}),'reject unreadable primary');
assert.ok(validateTheme({...DEFAULT_THEME,red:'#FBE7E8'}),'reject unreadable accent');
assert.ok(validateTheme({...DEFAULT_THEME,ink:'#FFFFFF'}),'reject unreadable text');
assert.equal(sanitizeTheme({...DEFAULT_THEME,red:'expression(javascript:alert(1))'}).red, DEFAULT_THEME.red);
assert.ok(contrastRatio(DEFAULT_THEME.navy,'#FFFFFF')>=4.5);
assert.ok(themeVariables(DEFAULT_THEME)['--luxury-ivory']);
const layout=text('app/(site)/layout.jsx');
assert(layout.includes('getPublicTheme()') && layout.includes('<SiteTheme'));
assert(layout.includes('<MobileDock'));
const admin=text('components/admin-workspace.jsx');
assert(admin.includes("id:'theme'") && admin.includes('ThemeEditor role={role}'));
assert(text('components/admin-panel.jsx').includes("'theme','homeHero','siteCopy'"));
const editor=text('components/theme-editor.jsx');
assert(editor.includes('setDoc') && editor.includes("role==='super_admin'"));
assert(editor.includes('serverTimestamp()') && editor.includes('validateTheme'));
const rules=text('firestore.rules');
assert(rules.includes("id in ['catalogue','publicCopy','theme','homeHero']"));
assert(rules.includes("id == 'theme' && validTheme()"));
assert(rules.includes('function validTheme()') && rules.includes('isSuperAdmin()'));
assert(rules.includes('palette.keys().hasOnly'));
assert(!text('package.json').includes('firebase-admin'));
assert(!fs.existsSync('node_modules') && !fs.existsSync('.next'));
assert(text('components/ui.jsx').includes("import { packageFallback } from '@/lib/package-image'"));
assert(text('app/luxury.css').includes('@media(max-width:690px)'));
console.log('PASS: V13 luxury theme, colour rules, Super Admin UI, mobile dock and prior image boundary.');
